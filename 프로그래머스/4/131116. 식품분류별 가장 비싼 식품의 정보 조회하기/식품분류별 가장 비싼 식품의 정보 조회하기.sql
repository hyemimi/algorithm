SELECT C.CATEGORY, C.MAX_PRICE, PRODUCT_NAME
FROM (
    SELECT CATEGORY, max(PRICE) as "MAX_PRICE"
    FROM FOOD_PRODUCT
    GROUP BY CATEGORY
    HAVING CATEGORY IN ('과자', '국', '김치', '식용유')
) C JOIN FOOD_PRODUCT P
ON C.CATEGORY = P.CATEGORY and P.PRICE = C.MAX_PRICE
ORDER BY C.MAX_PRICE DESC