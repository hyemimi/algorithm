SELECT P.MEMBER_NAME as "MEMBER_NAME", R2.REVIEW_TEXT as "REVIEW_TEXT", R2.REVIEW_DATE as "REVIEW_DATE"
FROM (
    SELECT MEMBER_ID,  count(*) as "CNT"
    FROM REST_REVIEW
    GROUP BY MEMBER_ID
    ORDER BY CNT DESC
    LIMIT 1
) R JOIN (
    (SELECT REVIEW_TEXT, REVIEW_DATE, MEMBER_ID
    FROM REST_REVIEW) R2 JOIN MEMBER_PROFILE P
    ON P.MEMBER_ID = R2.MEMBER_ID
) ON R.MEMBER_ID = P.MEMBER_ID
ORDER BY REVIEW_DATE, REVIEW_TEXT

